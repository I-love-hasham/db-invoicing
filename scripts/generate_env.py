#!/usr/bin/env python3
"""Create .env with fresh random secrets. Standard library only.

Usage (on the server, in the project folder):  python3 scripts/generate_env.py
Prints the SETUP_TOKEN once so you can create the admin account at /setup.
"""
import base64
import os
import secrets
import sys

path = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", ".env")
if os.path.exists(path):
    sys.exit(".env already exists — not overwriting it.")

setup_token = secrets.token_urlsafe(24)
values = {
    "SECRET_KEY": secrets.token_urlsafe(48),
    "AUDIT_HMAC_KEY": secrets.token_urlsafe(48),
    "ENCRYPTION_KEY": base64.urlsafe_b64encode(secrets.token_bytes(32)).decode(),
    "SETUP_TOKEN": setup_token,
    "COOKIE_SECURE": "1",
    "TRUST_PROXY_HEADERS": "1",
    "APP_TIMEZONE": "America/New_York",
}
fd = os.open(path, os.O_WRONLY | os.O_CREAT | os.O_EXCL, 0o600)
with os.fdopen(fd, "w") as fh:
    fh.write("# Generated by scripts/generate_env.py — keep private, never commit or share.\n")
    for k, v in values.items():
        fh.write(f"{k}={v}\n")
print("Created .env (permissions 600).")
print(f"Setup token (needed once at /setup): {setup_token}")
print("Back up .env somewhere safe and offline: without ENCRYPTION_KEY and AUDIT_HMAC_KEY")
print("the stored 2FA secret can't be decrypted and the audit log can't be verified.")
